/**
 * Source-bound applicability for the fields that this candidate can either
 * calculate, transfer from a reviewed fact, or deliberately leave unresolved.
 * `formId` is the stable package identifier; `satSection` and `satLabel` keep
 * the mapping to the SAT application visible without pretending that an
 * internal working-paper key is an electronic filing field name.
 */
export type Mexico2025FieldStatus =
  'implemented' | 'explicit-zero' | 'review-required' | 'unsupported';

