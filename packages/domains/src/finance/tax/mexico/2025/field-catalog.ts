const rule = (formId: string, fieldKey: string) =>
  `mx2025.${formId}.${fieldKey}`;

function field(
  taxpayerType: Mexico2025FieldApplicability['taxpayerType'],
  formId: string,
  satSection: string,
  fieldKey: string,
  satLabel: string,
  valueType: Mexico2025FieldApplicability['valueType'],
  status: Mexico2025FieldStatus,
  sourceReferenceIds: readonly string[],
  sourceLocator: string,
  requiredFactKeys: readonly string[] = [],
): Mexico2025FieldApplicability {
  return {
    id: `${taxpayerType}.${formId}.${fieldKey}`,
    taxpayerType,
    formId,
    satSection,
    fieldKey,
    satLabel,
    valueType,
    status,
    sourceReferenceIds,
    sourceLocator,
    requiredFactKeys,
    ruleId:
      status === 'unsupported' || status === 'review-required'
        ? null
        : rule(formId, fieldKey),
    emittedByEvaluator: status === 'implemented' || status === 'explicit-zero',
  };
}

