import { z } from 'zod';

import {
  FinanceBudgetVsActualsSchema,
  FinanceForecastSnapshotSchema,
  FinancePlanningCapabilitySchema,
  FinancePlanningRevisionSchema,
} from './finance-planning.js';
import { FinanceCurrencySchema } from './finance-v2.js';
import { IsoDateTimeSchema, Sha256Schema, UuidSchema } from './primitives.js';

/** The immutable source journal reference retained with a planning result. */
export const FinancePlanningResultSourceJournalSchema = z.strictObject({
  journalId: UuidSchema,
  effectiveOn: z.iso.date(),
  sourceReference: z.string().trim().min(1).max(200),
  payloadHash: Sha256Schema,
});

/** The reviewed inputs and source coverage used to materialize a result. */
export const FinancePlanningResultSourceLineageSchema = z
  .strictObject({
    budgetId: UuidSchema,
    budgetRevision: FinancePlanningRevisionSchema,
    review: z.strictObject({
      itemCount: z.number().int().safe().positive().max(10_000),
      currency: FinanceCurrencySchema,
      reviewForecastId: UuidSchema.nullable(),
      reviewForecastRevision: FinancePlanningRevisionSchema.nullable(),
    }),
    sourceJournals: z
      .array(FinancePlanningResultSourceJournalSchema)
      .max(10_000),
    canonicalIntentHash: Sha256Schema,
  })
  .superRefine((lineage, context) => {
    if (
      new Set(lineage.sourceJournals.map((journal) => journal.journalId))
        .size !== lineage.sourceJournals.length
    ) {
      context.addIssue({
        code: 'custom',
        path: ['sourceJournals'],
        message: 'Source journal identities must be unique',
      });
    }
  });

/** The deterministic payload generated by the planning automation leaf. */
export const FinancePlanningResultPayloadSchema = z.union([
  FinanceBudgetVsActualsSchema,
  FinanceForecastSnapshotSchema,
]);

/**
 * Immutable persisted planning automation output. The database trigger owns
 * immutability; this contract keeps the payload, lineage, and hash typed at
 * every API boundary without changing the existing automation contracts.
 */
const FinancePlanningAutomationResultBaseSchema = z.strictObject({
  id: UuidSchema,
  workspaceId: UuidSchema,
  bookId: UuidSchema,
  automationRunId: UuidSchema,
  schemaVersion: z.literal(1),
  capability: FinancePlanningCapabilitySchema,
  budgetId: UuidSchema,
  budgetRevision: FinancePlanningRevisionSchema,
  snapshotAt: IsoDateTimeSchema,
  payload: FinancePlanningResultPayloadSchema,
  sourceLineage: FinancePlanningResultSourceLineageSchema,
  sourceHash: Sha256Schema,
});

export const FinancePlanningAutomationResultSchema =
  FinancePlanningAutomationResultBaseSchema.superRefine((result, context) => {
    const add = (path: (string | number)[], message: string) =>
      context.addIssue({ code: 'custom', path, message });
    const payload = result.payload;
    if (
      payload.workspaceId !== result.workspaceId ||
      payload.bookId !== result.bookId ||
      payload.budgetId !== result.budgetId ||
      payload.budgetRevision !== result.budgetRevision ||
      payload.snapshotAt !== result.snapshotAt
    ) {
      add([], 'Planning result payload is outside the result identity scope');
    }
    if (
      result.sourceLineage.budgetId !== result.budgetId ||
      result.sourceLineage.budgetRevision !== result.budgetRevision
    ) {
      add(
        ['sourceLineage'],
        'Planning result lineage is outside the result identity scope',
      );
    }
    if (
      result.sourceLineage.review.currency !== payload.functionalCurrency ||
      result.sourceLineage.review.itemCount !==
        ('rows' in payload ? payload.rows.length : payload.lines.length)
    ) {
      add(
        ['sourceLineage', 'review'],
        'Planning result review facts do not match the payload',
      );
    }
    const isBudgetActuals = 'rows' in payload;
    if (
      (result.capability === 'finance.planning.budget-vs-actuals') !==
      isBudgetActuals
    ) {
      add(['capability'], 'Planning result capability does not match payload');
    }
    const review = result.sourceLineage.review;
    if (result.capability === 'finance.planning.forecast') {
      if (
        review.reviewForecastId === null ||
        review.reviewForecastRevision === null
      )
        add(
          ['sourceLineage', 'review'],
          'Forecast results require an immutable reviewed forecast reference',
        );
    } else if (
      review.reviewForecastId !== null ||
      review.reviewForecastRevision !== null
    ) {
      add(
        ['sourceLineage', 'review'],
        'Budget actual results cannot carry a forecast review reference',
      );
    }
    if (result.capability === 'finance.planning.forecast') {
      if (
        !('forecastId' in payload) ||
        payload.forecastId !== result.id ||
        payload.revision !== 1
      ) {
        add(
          ['payload'],
          'Forecast result payload must bind to its result identity',
        );
      }
    }
  });

/** Short alias used by callers that refer to the table as planning results. */
export const FinancePlanningResultSchema =
  FinancePlanningAutomationResultSchema;
export const FinancePlanningResultSummarySchema =
  FinancePlanningAutomationResultBaseSchema.omit({
    payload: true,
    sourceLineage: true,
  });

export type FinancePlanningResultSourceJournal = z.infer<
  typeof FinancePlanningResultSourceJournalSchema
>;
export type FinancePlanningResultSourceLineage = z.infer<
  typeof FinancePlanningResultSourceLineageSchema
>;
export type FinancePlanningResultPayload = z.infer<
  typeof FinancePlanningResultPayloadSchema
>;
export type FinancePlanningAutomationResult = z.infer<
  typeof FinancePlanningAutomationResultSchema
>;
export type FinancePlanningResult = FinancePlanningAutomationResult;
export type FinancePlanningResultSummary = z.infer<
  typeof FinancePlanningResultSummarySchema
>;
